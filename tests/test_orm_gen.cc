/**
 * @file test_orm_gen.cc
 * @brief ORM 代码生成器 PostgreSQL 方言测试
 *
 * 直接编译 chen/orm 源码，生成临时文件后断言关键 SQL 片段。
 * 不连接数据库。
 */
#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <iostream>
#include <sstream>
#include <string>

#include <unistd.h>

#include "chen/orm/table.h"
#include "chen/util/util.h"

namespace {

int g_failed = 0;

void check(bool cond, const char* what)
{
    if (!cond) {
        std::cerr << "[FAIL] " << what << std::endl;
        ++g_failed;
    }
}

std::string readFile(const std::string& path)
{
    std::ifstream ifs(path);
    if (!ifs) {
        std::cerr << "[FAIL] cannot open " << path << std::endl;
        ++g_failed;
        return "";
    }
    std::stringstream ss;
    ss << ifs.rdbuf();
    return ss.str();
}

bool initTable(chen::orm::Table& table, const char* xml)
{
    tinyxml2::XMLDocument doc;
    if (doc.Parse(xml) != tinyxml2::XML_SUCCESS) {
        return false;
    }
    return table.init(*doc.RootElement());
}

std::string generate(chen::orm::Table& table, const std::string& dir)
{
    table.gen(dir);
    return readFile(dir + "/test/data/" + table.getFileName() + ".cc");
}

const char* kPgXml = R"(
<table name="pg_user" namespace="test.data" db="postgresql" desc="PG user">
    <columns>
        <column name="id" type="int64" auto_increment="true"/>
        <column name="name" type="string" length="64" default="guest" desc="name"/>
        <column name="score" type="uint64" default="0"/>
        <column name="created_at" type="timestamp" update="current_timestamp" desc="created"/>
        <column name="data" type="blob"/>
        <column name="note" type="text"/>
    </columns>
    <indexs>
        <index name="PK" type="pk" cols="id"/>
        <index name="uniq_name" type="uniq" cols="name"/>
        <index name="idx_score" type="index" cols="score"/>
    </indexs>
</table>
)";

const char* kSqliteXml = R"(
<table name="lite_user" namespace="test.data">
    <columns>
        <column name="id" type="int64" auto_increment="true"/>
        <column name="name" type="string" default=""/>
    </columns>
    <indexs>
        <index name="PK" type="pk" cols="id"/>
    </indexs>
</table>
)";

const char* kMysqlXml = R"(
<table name="my_user" namespace="test.data" db="mysql">
    <columns>
        <column name="id" type="int64" auto_increment="true"/>
        <column name="name" type="string" default=""/>
    </columns>
    <indexs>
        <index name="PK" type="pk" cols="id"/>
    </indexs>
</table>
)";

const char* kPgUint64AutoXml = R"(
<table name="bad_pg" namespace="test.data" db="postgresql">
    <columns>
        <column name="id" type="uint64" auto_increment="true"/>
    </columns>
    <indexs>
        <index name="PK" type="pk" cols="id"/>
    </indexs>
</table>
)";

const char* kPgMultiAutoXml = R"(
<table name="bad_pg2" namespace="test.data" db="postgresql">
    <columns>
        <column name="id" type="int64" auto_increment="true"/>
        <column name="seq" type="int64" auto_increment="true"/>
    </columns>
    <indexs>
        <index name="PK" type="pk" cols="id"/>
    </indexs>
</table>
)";

const char* kBadDbXml = R"(
<table name="bad_db" namespace="test.data" db="oracle">
    <columns>
        <column name="id" type="int64"/>
    </columns>
    <indexs>
        <index name="PK" type="pk" cols="id"/>
    </indexs>
</table>
)";

} // namespace

int main()
{
    const std::string dir = "/tmp/chen_orm_gen_" + std::to_string(getpid());
    std::filesystem::remove_all(dir);

    chen::orm::Table pg;
    check(initTable(pg, kPgXml), "postgresql table init");
    std::string pgSrc = generate(pg, dir);

    check(pgSrc.find("CREATE TABLE IF NOT EXISTS \\\"pg_user\\\"(") != std::string::npos, "postgresql create table");
    check(pgSrc.find("\\\"id\\\" bigint GENERATED BY DEFAULT AS IDENTITY") != std::string::npos, "postgresql identity column");
    check(pgSrc.find("\\\"name\\\" character varying(64) NOT NULL DEFAULT 'guest'") != std::string::npos, "postgresql varchar default");
    check(
        pgSrc.find("\\\"created_at\\\" timestamp without time zone NOT NULL DEFAULT '1970-01-01 00:00:00'") != std::string::npos,
        "postgresql timestamp default");
    check(pgSrc.find("\\\"data\\\" bytea NOT NULL DEFAULT ''::bytea") != std::string::npos, "postgresql bytea default");
    check(pgSrc.find("PRIMARY KEY(\\\"id\\\")") != std::string::npos, "postgresql primary key");
    check(
        pgSrc.find("CREATE UNIQUE INDEX IF NOT EXISTS \\\"pg_user_name\\\" ON \\\"pg_user\\\"(\\\"name\\\")") != std::string::npos,
        "postgresql unique index");
    check(
        pgSrc.find("CREATE OR REPLACE FUNCTION \\\"pg_user_update\\\"() RETURNS trigger") != std::string::npos, "postgresql update trigger function");
    check(pgSrc.find("CREATE TRIGGER \\\"pg_user_update\\\" BEFORE UPDATE ON \\\"pg_user\\\"") != std::string::npos, "postgresql update trigger");
    check(pgSrc.find("insert into \\\"pg_user\\\" (\\\"name\\\"") != std::string::npos, "postgresql insert quoted table/column");
    check(pgSrc.find("returning \\\"id\\\"") != std::string::npos, "postgresql insert returning");
    check(pgSrc.find("on conflict (\\\"id\\\") do update set") != std::string::npos, "postgresql upsert conflict target");
    check(pgSrc.find("excluded.\\\"name\\\"") != std::string::npos, "postgresql upsert excluded column");
    check(pgSrc.find("MigrateTablePostgreSQL") != std::string::npos, "postgresql migration method");
    check(pgSrc.find("to_regclass(?)") != std::string::npos, "postgresql migration catalog query");
    check(pgSrc.find("ADD GENERATED BY DEFAULT AS IDENTITY") != std::string::npos, "postgresql migration identity sync");
    check(pgSrc.find("ALTER COLUMN") != std::string::npos, "postgresql migration alter column");
    check(pgSrc.find("std::string table = \"\\\"pg_user\\\"\";") != std::string::npos, "postgresql newQuery table name");

    chen::orm::Table sqlite;
    check(initTable(sqlite, kSqliteXml), "sqlite table init");
    std::string sqliteSrc = generate(sqlite, dir);
    check(sqliteSrc.find("if (CreateTableSQLite3(conn)) {") != std::string::npos, "sqlite migrate branch");
    check(sqliteSrc.find("if (CreateTablePostgreSQL(conn)) {") == std::string::npos, "sqlite does not use postgresql migrate branch");

    chen::orm::Table mysql;
    check(initTable(mysql, kMysqlXml), "mysql table init");
    std::string mysqlSrc = generate(mysql, dir);
    check(mysqlSrc.find("if (CreateTableMySQL(conn)) {") != std::string::npos, "mysql migrate branch");
    check(mysqlSrc.find("if (CreateTableSQLite3(conn)) {") == std::string::npos, "mysql does not use sqlite migrate branch");

    chen::orm::Table badAuto;
    check(!initTable(badAuto, kPgUint64AutoXml), "postgresql rejects uint64 auto_increment");
    chen::orm::Table badMulti;
    check(!initTable(badMulti, kPgMultiAutoXml), "postgresql rejects multiple auto_increment columns");
    chen::orm::Table badDb;
    check(!initTable(badDb, kBadDbXml), "invalid db attribute rejected");

    std::filesystem::remove_all(dir);

    if (g_failed) {
        std::cerr << g_failed << " check(s) failed" << std::endl;
        return 1;
    }
    std::cout << "test_orm_gen passed" << std::endl;
    return 0;
}
