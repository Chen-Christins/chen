/**
 * @file test_postgresql.cc
 * @brief PostgreSQL 驱动集成测试
 *
 * 需要设置 CHEN_TEST_PG_HOST 才会执行；其余参数可用：
 * CHEN_TEST_PG_PORT / CHEN_TEST_PG_USER / CHEN_TEST_PG_PASSWD / CHEN_TEST_PG_DBNAME。
 */
#include <cstdlib>
#include <iostream>
#include <map>
#include <string>

#include "chen/db/postgresql.h"

namespace {

int g_failed = 0;

void check(bool cond, const char* what, const std::string& detail = "")
{
    if (!cond) {
        std::cerr << "[FAIL] " << what;
        if (!detail.empty()) {
            std::cerr << ": " << detail;
        }
        std::cerr << std::endl;
        ++g_failed;
    }
}

std::string envOr(const char* name, const char* def)
{
    const char* v = std::getenv(name);
    return (v && *v) ? v : def;
}

} // namespace

int main()
{
    const char* host = std::getenv("CHEN_TEST_PG_HOST");
    if (!host || !*host) {
        std::cout << "test_postgresql skipped: CHEN_TEST_PG_HOST is not set" << std::endl;
        return 0;
    }

    std::map<std::string, std::string> params;
    params["host"] = host;
    params["port"] = envOr("CHEN_TEST_PG_PORT", "5432");
    params["user"] = envOr("CHEN_TEST_PG_USER", "postgres");
    params["passwd"] = envOr("CHEN_TEST_PG_PASSWD", "");
    params["dbname"] = envOr("CHEN_TEST_PG_DBNAME", "postgres");

    chen::PostgreSQL::ptr db(new chen::PostgreSQL(params));
    check(db->connect(), "connect", db->getErrStr());
    if (g_failed) {
        return 1;
    }
    check(db->ping(), "ping", db->getErrStr());

    check(db->execute("DROP TABLE IF EXISTS chen_pg_test") == 0, "drop table", db->getErrStr());
    check(
        db->execute(
            "CREATE TABLE chen_pg_test ("
            "id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            "name character varying(64) NOT NULL DEFAULT '', "
            "data bytea NOT NULL DEFAULT ''::bytea, "
            "ts timestamp without time zone NOT NULL DEFAULT '1970-01-01 00:00:00', "
            "n integer NOT NULL DEFAULT 0)")
            == 0,
        "create table", db->getErrStr());

    std::string blob("\x00\x01\xff", 3);
    auto insert = db->prepare("INSERT INTO chen_pg_test (name, data, ts, n) VALUES (?, ?, ?, ?) RETURNING id");
    check(insert != nullptr, "prepare insert", db->getErrStr());
    if (insert) {
        check(insert->bindString(1, "alice") == 0, "bind name");
        check(insert->bindBlob(2, blob) == 0, "bind blob");
        check(insert->bindTime(3, 1700000000) == 0, "bind time");
        check(insert->bindInt32(4, 7) == 0, "bind int");
        auto rt = insert->query();
        check(rt != nullptr, "insert returning", insert->getErrStr());
        if (rt) {
            check(rt->next(), "insert returning row");
            check(rt->getInt64(0) > 0, "insert returning id");
        }
    }

    auto row = db->query("SELECT id, name, data, ts, n FROM chen_pg_test WHERE name = 'alice'");
    check(row != nullptr, "query row", db->getErrStr());
    if (row) {
        check(row->next(), "query row data");
        check(row->getString(1) == "alice", "query name");
        check(row->getBlob(2) == blob, "query blob");
        check(row->getTime(3) == 1700000000, "query time");
        check(row->getInt32(4) == 7, "query int");
    }

    // 字符串/dollar quote 中的 ? 不应被改写为占位符
    auto placeholder = db->prepare("SELECT '?' AS literal, ? AS value");
    check(placeholder != nullptr, "prepare quoted placeholder", db->getErrStr());
    if (placeholder) {
        placeholder->bindInt32(1, 42);
        auto rt = placeholder->query();
        check(rt != nullptr, "quoted placeholder query", placeholder->getErrStr());
        if (rt) {
            check(rt->next(), "quoted placeholder row");
            check(rt->getString(0) == "?", "quoted placeholder literal");
            check(rt->getInt32(1) == 42, "quoted placeholder value");
        }
    }

    auto dollar = db->prepare("SELECT $$?$$ AS literal, ? AS value");
    check(dollar != nullptr, "prepare dollar quote", db->getErrStr());
    if (dollar) {
        dollar->bindInt32(1, 43);
        auto rt = dollar->query();
        check(rt != nullptr, "dollar quote query", dollar->getErrStr());
        if (rt) {
            check(rt->next(), "dollar quote row");
            check(rt->getString(0) == "?", "dollar quote literal");
            check(rt->getInt32(1) == 43, "dollar quote value");
        }
    }

    check(db->execute("INSERT INTO chen_pg_test (name) VALUES ('lastval')") == 0, "insert lastval", db->getErrStr());
    check(db->getLastInsertId() > 0, "getLastInsertId", db->getErrStr());

    auto trx = db->openTransaction(false);
    check(trx != nullptr, "open transaction", db->getErrStr());
    if (trx) {
        check(trx->execute("INSERT INTO chen_pg_test (name) VALUES ('rollback')") == 0, "transaction insert", db->getErrStr());
        check(trx->rollback(), "transaction rollback");
    }
    auto rollbackCount = db->query("SELECT COUNT(*) FROM chen_pg_test WHERE name = 'rollback'");
    check(rollbackCount != nullptr && rollbackCount->next() && rollbackCount->getInt64(0) == 0, "rollback visible row count");

    // 自动提交事务在出错后销毁时应回滚，不能把未提交数据留在连接池连接里
    {
        auto autoTrx = db->openTransaction(true);
        check(autoTrx != nullptr, "open auto transaction", db->getErrStr());
        if (autoTrx) {
            check(autoTrx->execute("INSERT INTO chen_pg_test (name) VALUES ('auto_rollback')") == 0, "auto transaction insert", db->getErrStr());
            autoTrx->execute("SELECT * FROM chen_pg_missing_table");
        }
    }
    auto autoRollbackCount = db->query("SELECT COUNT(*) FROM chen_pg_test WHERE name = 'auto_rollback'");
    check(autoRollbackCount != nullptr && autoRollbackCount->next() && autoRollbackCount->getInt64(0) == 0, "auto transaction rollback on error");

    check(db->execute("DROP TABLE chen_pg_test") == 0, "drop table cleanup", db->getErrStr());

    if (g_failed) {
        std::cerr << g_failed << " check(s) failed" << std::endl;
        return 1;
    }
    std::cout << "test_postgresql passed" << std::endl;
    return 0;
}
